import { z } from "zod";

// ------------------------------------------------------------------------------------------------
// PAYLOAD - SCHEMAS
// ------------------------------------------------------------------------------------------------
export const C_SignInDTOSchema = z.object({
  email: z.string().trim().toLowerCase().pipe(z.email()),
  password: z.string().min(1),
});

// ------------------------------------------------------------------------------------------------
// INFER - DTO TYPES
// ------------------------------------------------------------------------------------------------
export type C_SignInDTO = z.infer<typeof C_SignInDTOSchema>;
